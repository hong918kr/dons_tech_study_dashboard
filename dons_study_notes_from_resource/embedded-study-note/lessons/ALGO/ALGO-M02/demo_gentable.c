/* ALGO-M02 테이블 생성기: 빌드 때 한 번 돌려 const 테이블 C 소스를 만든다 (펌웨어에서는 플래시 .rodata 로).
 * ./demo_gentable      → crc32_tab[256]        (1 KiB)
 * ./demo_gentable 8    → crc32_tab8[8][256]    (8 KiB, slicing-by-8 용)
 * 빌드: cc -std=c11 -Wall -Wextra -Werror -O2 demo_gentable.c -o demo_gentable
 */
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>

#define POLY_R 0xEDB88320u

int main(int argc, char **argv) {
    static uint32_t t[8][256];
    int k_max = (argc > 1) ? atoi(argv[1]) : 1;
    if (k_max != 1 && k_max != 4 && k_max != 8) { fprintf(stderr, "usage: %s [1|4|8]\n", argv[0]); return 2; }
    for (uint32_t i = 0; i < 256; i++) {
        uint32_t c = i;
        for (int k = 0; k < 8; k++) c = (c >> 1) ^ (POLY_R & (0u - (c & 1u)));
        t[0][i] = c;
    }
    for (int k = 1; k < k_max; k++)
        for (int i = 0; i < 256; i++) t[k][i] = (t[k - 1][i] >> 8) ^ t[0][t[k - 1][i] & 0xFFu];

    printf("/* generated by demo_gentable.c — CRC-32/ISO-HDLC, reflected poly 0x%08X */\n", POLY_R);
    printf("#include <stdint.h>\n");
    if (k_max == 1) printf("const uint32_t crc32_tab[256] = {\n");
    else printf("const uint32_t crc32_tab%d[%d][256] = {\n", k_max, k_max);
    for (int k = 0; k < k_max; k++) {
        if (k_max > 1) printf("  {\n");
        for (int i = 0; i < 256; i++)
            printf("%s0x%08X%s", (i % 6 == 0) ? "    " : " ", t[k][i], (i == 255) ? "\n" : (i % 6 == 5) ? ",\n" : ",");
        if (k_max > 1) printf("  }%s\n", k + 1 < k_max ? "," : "");
    }
    printf("};\n");
    return 0;
}
