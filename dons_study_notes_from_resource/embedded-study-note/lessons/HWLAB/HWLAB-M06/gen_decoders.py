#!/usr/bin/env python3
"""HWLAB-M06 디코더 패키지 내보내기 (결정적).

solution.py 의 `# ==== pd:<id> begin ====` ~ `# ==== pd:<id> end ====` 구역을 그대로 잘라
sigrok 프로토콜 디코더 패키지 모양으로 쓴다:

  decoders/<id>/__init__.py   docstring + `from .pd import Decoder`
  decoders/<id>/pd.py         `import sigrokdecode as srd` + 구역 코드 (클래스 이름만 Decoder 로)

이 디렉터리를 libsigrokdecode 의 디코더 검색 경로(SIGROKDECODE_DIR 등)에 두면 sigrok-cli / PulseView 가
같은 코드를 읽는다 (이 맥에는 sigrok 이 없어 실제 로드는 확인하지 못했다 — md 참고).

  python3 -I gen_decoders.py
"""
import hashlib
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PDS = {
    "ws2812_lab": ("Ws2812Lab", "WS2812/WS2812B RGB LED chain decoder with timing checks (HWLAB-M06).\n\n"
                   "Single-wire NRZ: a bit is a high pulse (T0H ~0.4 us = 0, T1H ~0.8 us = 1) in a ~1.25 us\n"
                   "period; 24 bits per LED (GRB, MSB first); a low longer than the reset time latches the chain."),
    "tmp117_lab": ("Tmp117Lab", "TI TMP117 temperature sensor register decoder, stacked on I2C (HWLAB-M06).\n\n"
                   "Pointer write + 16-bit register read/write; Temp_Result is shown in degrees C (1 LSB = 1/128 C)."),
}
HEADER = """##
## HWLAB-M06 study decoder ({id}) — generated by gen_decoders.py from solution.py. Do not edit by hand.
## License: GPL-2.0-or-later (the libsigrokdecode decoder convention, 'gplv2+').
##

import sigrokdecode as srd

"""


def extract(src, pd_id):
    m = re.search(r"^# ==== pd:%s begin ====\n(.*?)^# ==== pd:%s end ====\n" % (pd_id, pd_id), src, re.S | re.M)
    if not m:
        raise SystemExit("region pd:%s not found" % pd_id)
    return m.group(1)


def build(outdir=HERE):
    with open(os.path.join(HERE, "solution.py"), encoding="utf-8") as f:
        src = f.read()
    written = []
    for pd_id, (cls, doc) in PDS.items():
        body = extract(src, pd_id)
        body, n = re.subn(r"^class %s\(srd\.Decoder\):" % cls, "class Decoder(srd.Decoder):", body, flags=re.M)
        if n != 1:
            raise SystemExit("class %s not found in region %s" % (cls, pd_id))
        d = os.path.join(outdir, "decoders", pd_id)
        os.makedirs(d, exist_ok=True)
        files = {"__init__.py": "'''\n%s\n'''\n\nfrom .pd import Decoder\n" % doc,
                 "pd.py": HEADER.format(id=pd_id) + body.rstrip("\n") + "\n"}
        for name, text in files.items():
            pth = os.path.join(d, name)
            with open(pth, "w", encoding="utf-8", newline="\n") as f:
                f.write(text)
            written.append(pth)
    return written


def main():
    for pth in build():
        with open(pth, "rb") as f:
            blob = f.read()
        print("%-30s %5d B  sha256 %s" % (os.path.relpath(pth, HERE), len(blob), hashlib.sha256(blob).hexdigest()[:16]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
