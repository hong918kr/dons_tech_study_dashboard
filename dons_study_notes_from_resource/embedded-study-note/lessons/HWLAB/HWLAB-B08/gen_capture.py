#!/usr/bin/env python3
"""HWLAB-B08 합성 벅(buck) 출력 캡처 생성기 — 결정적(deterministic)

실제 계측기 캡처가 아니다. 벅 컨버터 출력 노드를 이렇게 합성한다:

  v(t) = Vout(DC)
       + (1/C) * ∫ i_ac dt      출력 커패시터 충방전 리플 (포물선 조각, pk-pk = ΔI/(8·fsw·C))
       + ESR * i_ac             ESR 리플 (삼각파, pk-pk = ΔI·ESR)
       + ESL * di_ac/dt         ESL 계단 (사각파)
       + 스위칭 스파이크         스위치 노드 에지마다 감쇠 정현파 A·exp(-t/τ)·sin(2π·f_ring·t)
       + 백색 잡음               N(0, σ) — 10x 프로브 + 스코프 입력 잡음(전대역)

  i_ac : 인덕터 전류의 AC 성분. on 구간(D·T) 동안 -ΔI/2 → +ΔI/2, off 구간 동안 다시 -ΔI/2 (삼각파)
  ΔI   = (Vin - Vout)·D / (L·fsw),  D = Vout/Vin (이상적 벅, 손실 무시)

  python3 -I gen_capture.py      # cap_VDD_1V8.csv 를 다시 쓰고 sha256 출력

다른 레일(VDD_0V8, VDD_3V3)은 파일로 쓰지 않고 synth() 로 메모리에서 만든다 (같은 seed → 같은 값).
"""
import hashlib
import math
import os
import random
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
FS = 2.5e9          # 2.5 GS/s  (dt = 0.4 ns)
RECORD = 4e-6       # 4 us = 10,000 samples
N = int(round(RECORD * FS))

# 보드 위의 "실제" 물리 파라미터 (분석하는 사람은 모른다고 가정 — 결함이 여기 심어져 있다)
RAILS = {
    # 정상 레일. 리플은 작지만 스위칭 스파이크가 커서 전대역(full BW) Vpp 로는 30 mV 스펙을 넘는다.
    "VDD_1V8": dict(vout=1.8030, vin=5.0, fsw=2e6, L=1.0e-6, C=4.7e-6, esr=0.010, esl=0.3e-9,
                    spike_rise=0.032, spike_fall=-0.022, f_ring=180e6, tau=4e-9,
                    noise=1.5e-3, phase=0.30, seed=1808),
    # 결함: 출력 벌크 커패시터 C412/C413 (22 uF x2) 미실장 → SoC 쪽 디커플링 ~4 uF 만 남음
    "VDD_0V8": dict(vout=0.8008, vin=3.3, fsw=1e6, L=0.47e-6, C=4.0e-6, esr=0.003, esl=0.3e-9,
                    spike_rise=0.020, spike_fall=-0.016, f_ring=220e6, tau=3e-9,
                    noise=1.5e-3, phase=0.55, seed=808),
    # 결함: 피드백 상단 저항 45.3k 대신 43.2k 실장 → 0.6 V x (1 + 43.2/10) = 3.192 V (-3.27 %)
    "VDD_3V3": dict(vout=3.192, vin=5.0, fsw=2e6, L=1.5e-6, C=10e-6, esr=0.005, esl=0.3e-9,
                    spike_rise=0.020, spike_fall=-0.016, f_ring=150e6, tau=5e-9,
                    noise=1.5e-3, phase=0.10, seed=3303),
}


def synth(name, **override):
    """레일 이름 → (t[s], v[V]) 리스트. override 로 noise=0, spike_rise=0 ... 처럼 성분을 끌 수 있다."""
    p = dict(RAILS[name])
    p.update(override)
    n = p.get("n", N)
    fs = p.get("fs", FS)
    T = 1.0 / p["fsw"]
    D = p["vout"] / p["vin"]
    dI = (p["vin"] - p["vout"]) * D / (p["L"] * p["fsw"])
    Ton, Toff = D * T, (1.0 - D) * T
    qmean = dI * T * (1.0 - 2.0 * D) / 12.0     # 한 주기 동안 ∫i_ac 의 평균 (풀이 참고)
    w = 2.0 * math.pi * p["f_ring"]
    span = 10.0 * p["tau"]
    rng = random.Random(p["seed"])
    t_out, v_out = [], []
    for k in range(n):
        t = k / fs
        x = math.fmod(t + p["phase"] * T, T)   # 주기 안의 위치, 0 = high-side ON 에지
        if x < Ton:
            i = -dI / 2 + dI * x / Ton
            q = -dI * x / 2 + dI * x * x / (2 * Ton)
            didt = dI / Ton
        else:
            y = x - Ton
            i = dI / 2 - dI * y / Toff
            q = dI * y / 2 - dI * y * y / (2 * Toff)
            didt = -dI / Toff
        v = p["vout"] + (q - qmean) / p["C"] + p["esr"] * i + p["esl"] * didt
        if x < span:                                   # ON 에지(스위치 노드 상승) 직후 링잉
            v += p["spike_rise"] * math.exp(-x / p["tau"]) * math.sin(w * x)
        y = x - Ton
        if 0.0 <= y < span:                            # OFF 에지(스위치 노드 하강) 직후 링잉
            v += p["spike_fall"] * math.exp(-y / p["tau"]) * math.sin(w * y)
        if p["noise"]:
            v += rng.gauss(0.0, p["noise"])
        t_out.append(t)
        v_out.append(v)
    return t_out, v_out


def csv_text(name):
    """스코프 export 비슷한 CSV 텍스트 (주석 헤더 + time_ns,volt_V)."""
    t, v = synth(name)
    lines = [
        "# SYNTHETIC capture generated by gen_capture.py (HWLAB-B08) -- not a real instrument export",
        "# rail=%s  fs=%.4g Sa/s  record=%.4g s  bw=full  probe=10x passive, spring-tip ground" % (name, FS, RECORD),
        "time_ns,volt_V",
    ]
    for ti, vi in zip(t, v):
        lines.append("%.1f,%.5f" % (ti * 1e9, vi))
    return "\n".join(lines) + "\n"


def main():
    text = csv_text("VDD_1V8")
    path = os.path.join(HERE, "cap_VDD_1V8.csv")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote %s  lines=%d  bytes=%d  sha256=%s" % (
        os.path.basename(path), text.count("\n"), len(text.encode()),
        hashlib.sha256(text.encode()).hexdigest()[:16]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
